export interface ChatMessage {
  role: 'user' | 'model' | 'system'; // System role for Gemini Chat
  parts: Part[]; // Using Gemini's Part type
  timestamp: number;
  imagePreview?: string; // base64 data URL for displaying sent/received images in chat UI
}

export interface ActiveTask {
  id: string;
  type: string; 
  description: string;
  stop: () => void; 
}

export type GeminiChatInstance = GeminiChat;

export interface GeneratedImage {
  image: {
    imageBytes: string; 
    mimeType: string;
  };
  altText?: string;
}

export interface GroundingChunk {
  web?: {
    uri?: string; 
    title?: string; 
  };
  retrievedContext?: {
    uri?: string; 
    title?: string; 
  };
}

export interface GroundingMetadata {
  webSearchQueries?: string[];
  groundingChunks?: GroundingChunk[];
}

export interface CustomGenerateContentResponse extends GenerateContentResponse {
   candidates?: (GenerateContentResponse['candidates'][0] & { groundingMetadata?: GroundingMetadata })[];
}

// For Gemini-Dvach conversations
export interface GeminiDvachConversation {
  dvachRootPostByGeminiNum: string; // The Dvach post number where Gemini started this conversation
  board: string;
  threadId: string;
  geminiChatInstance?: GeminiChatInstance; // Stored chat instance
  history: ChatMessage[]; // Full history including initial prompt
  lastCheckedTimestamp: number; // To know when we last looked for replies
}
