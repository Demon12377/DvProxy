
import { GenerateContentResponse, Chat as GeminiChat, Part } from "@google/genai";

export interface DvachFile {
  name: string;
  path: string;
  thumbnail: string;
  md5: string;
  type: number; // 0: image, 10: webm video with sound, etc.
  width: number;
  height: number;
  size: number; // in bytes
  tn_width: number;
  tn_height: number;
}
export interface DvachPost {
  num: string; // Can be string or number from API, ensure consistent usage
  parent: string;
  comment: string;
  timestamp: number;
  files?: DvachFile[];
  subject?: string;
  name?: string; // Poster name
  lasthit?: number; // Timestamp of last reply, for OP
  op?: number; // 1 if OP
}

export interface DvachThreadData { // Structure for board/res/thread.json
  posts: DvachPost[];
  current_thread: string;
  // other thread-specific fields if any
}
export interface DvachCatalogThread { // Structure for catalog.json
    num: string;
    comment: string;
    timestamp: number;
    subject: string;
    views: number;
    posts_count: number;
    files_count: number;
    files?: DvachFile[]; // Typically one preview file
    op?: number;
    name?: string;
}

export interface DvachThread { // Used by getDvachThread, which fetches board/res/thread.json
  threads: DvachThreadData[]; // This is an array with one element for the specific thread
  // It can also represent the catalog structure if fetching catalog.json
  // For simplicity, let's assume getDvachThread fetches a single thread structure like thread.json
  // If fetching catalog.json, the structure is different: an object with board info and a `threads` array of DvachCatalogThread
}


export interface SentMessageInfo {
  num: string; 
  timestamp: number; 
  comment: string;
  file_hash?: string;
  parent?: string; 
  board: string;
  thread: string;
  isGeminiPost?: boolean; // True if this post was generated by Gemini
  geminiTriggerPostNum?: string; // If Gemini replied to a specific post
  geminiConversationId?: string; // To link to a specific Gemini chat session if applicable
}

export interface AppSettings {
  board: string;
  threadId: string;
  passcode: string;
  geminiApiKeySource: 'env' | 'user';
  userGeminiApiKey: string;
  useRandomDelayNormal: boolean;
  useRandomDelaySecure: boolean;
  allowReplyToSelf: boolean;
  currentDomainIndex: number;
  theme: 'light' | 'dark' | 'system';
  geminiReplyWithImage: boolean; 
  autoMonitorDvachThreadForGemini: boolean;
  proxyMode: 'cors-anywhere' | 'custom' | 'none'; // New proxy setting
  customProxyUrl: string; // New proxy setting for custom URL
}

export interface LogEntry {
  id: string;
  timestamp: number;
  message: string;
  type: 'info' | 'error' | 'success' | 'warning' | 'gemini' | 'dvach';
  data?: unknown;
}

